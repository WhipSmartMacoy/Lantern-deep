# Generates lantern_vig.svh: the vignette row table used by the scan-out (mirrors GOP_PRESENT in src/gpu.c).
import math, sys
W, H = 266, 240
def tdiv(a, b):  # C integer division (truncates toward zero)
    q = abs(a) // abs(b)
    return q if (a >= 0) == (b >= 0) else -q
rows = []
for y in range(H):
    t = []
    for b in range(3):
        thr = (620, 800, 960)[b]
        dy = tdiv((y - H // 2 + 8) * 1000, H // 2 + 20)
        rem = thr * 1000 - dy * dy
        r = math.isqrt(rem) if rem > 0 else 0
        t.append(min(W // 2, 0 if rem <= 0 else tdiv(r * (W // 2 + 10), 1000)))
    rows.append(t)
out = ["// generated by hw/gen_vig.py - vignette band edges per row: {edge2, edge1, edge0} (distance from centre)",
       "function automatic [23:0] vig_row(input [7:0] y);", "  case (y)"]
for y, t in enumerate(rows):
    out.append(f"    8'd{y}: vig_row = {{8'd{t[2]}, 8'd{t[1]}, 8'd{t[0]}}};")
out += ["    default: vig_row = {8'd255, 8'd255, 8'd255};", "  endcase", "endfunction", ""]
open(sys.argv[1], "w").write("\n".join(out))
