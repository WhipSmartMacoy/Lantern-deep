def encode():
    out = []
    for c in range(32, 96):
        rows = G[chr(c)]; assert len(rows) == 7 and all(len(r) == 4 for r in rows), chr(c)
        v = 0
        for y, r in enumerate(rows):
            for x, ch in enumerate(r):
                if ch == '#': v |= 1 << (y * 4 + x)
        out.append(v)
    return out
if __name__ == '__main__':
    print(len(encode()))
